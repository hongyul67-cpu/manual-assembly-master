  function symRow(group, cols) {
    var names = (typeof SYMGROUP !== 'undefined' && SYMGROUP[group]) || [];
    var cells = names.map(function (n) {
      return '<div style="text-align:center">' +
             '<div style="height:78px">' + SYM[n] + '</div>' +
             '<b style="display:block;font-size:13px;color:#1c2430;line-height:1.25;' +
             'margin-top:3px;word-break:keep-all">' + n + '</b></div>';
    }).join('');
    return box('<div style="display:grid;gap:9px;grid-template-columns:repeat(' +
               (cols || Math.min(names.length, 5)) + ',minmax(0,1fr))">' + cells + '</div>', 10);
  }

